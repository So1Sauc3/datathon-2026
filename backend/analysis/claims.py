"""Registry behind the Claims & Evidence appendix: every finding names its query, result,
the alternative explanation that was tested, and its limitation."""
from dataclasses import asdict, dataclass, field


@dataclass
class Claim:
    id: str
    question: str
    claim: str
    evidence: str
    result: str
    alternative: str
    limitation: str
    tags: list[str] = field(default_factory=list)


REGISTRY: dict[str, Claim] = {}


def add(id: str, question: str, claim: str, evidence: str, result: str, alternative: str,
        limitation: str, tags: list[str] | None = None) -> Claim:
    item = Claim(id, question, claim, evidence, result, alternative, limitation, tags or [])
    REGISTRY[id] = item
    return item


def as_records() -> list[dict]:
    return [asdict(c) for c in REGISTRY.values()]


def to_markdown() -> str:
    lines = [
        "# Claims & Evidence appendix",
        "",
        "Generated by `python -m analysis.run`. The Gilded Ace is fictional and its data synthetic;"
        " only `4_context/real_sources/` is real public data.",
        "",
    ]
    for question in dict.fromkeys(c.question for c in REGISTRY.values()):
        lines += [f"## {question}", ""]
        for c in (c for c in REGISTRY.values() if c.question == question):
            lines += [
                f"### {c.id}: {c.claim}",
                "",
                f"- **Table / query:** {c.evidence}",
                f"- **Result:** {c.result}",
                f"- **Alternative explanation tested:** {c.alternative}",
                f"- **Limitation:** {c.limitation}",
                "",
            ]
    return "\n".join(lines)
